alter table public.talki_agenda_events
  drop constraint if exists talki_agenda_events_tipo_check;
alter table public.talki_agenda_events
  add constraint talki_agenda_events_tipo_check
  check(tipo in ('reuniao', 'entrega', 'tarefa'));

create or replace function talki_private.agenda_task_sync_trigger()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.tipo = 'tarefa' then
    perform talki_private.sync_agenda_task(new);
  else
    delete from public.tasks
    where id = (
      select task_id from talki_private.agenda_task_links where event_id = new.id
    );
  end if;
  return new;
end;
$$;

revoke all on function talki_private.agenda_task_sync_trigger()
  from public, anon, authenticated;

drop trigger if exists agenda_task_sync on public.talki_agenda_events;
create trigger agenda_task_sync
after insert or update of plan_id, titulo, descricao, tipo, inicio, fim, dia_inteiro, local, link
on public.talki_agenda_events
for each row execute function talki_private.agenda_task_sync_trigger();

-- Remove only tasks generated by the previous Agenda automation. Calendar
-- events and ordinary Kanban tasks are untouched.
delete from public.tasks
where id in (
  select links.task_id
  from talki_private.agenda_task_links links
  join public.talki_agenda_events events on events.id = links.event_id
  where events.tipo <> 'tarefa'
);
